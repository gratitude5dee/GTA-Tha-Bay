import { existsSync, mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { repoRoot } from '../../ci/run.ts';
import { isDeniedHost, loadSources, validateSources, type SourcesConfig } from '../src/config.ts';
import { ATTRIBUTION_PATH, attributionFor, buildAttribution, terrariumAccessDate } from '../src/pack/attribution.ts';
import { fetchBuffer } from '../src/sources/net.ts';
import { fillCommand, osmCommands, runFetch } from '../src/stages/s0-fetch.ts';
import { stableJson } from '../src/util.ts';

// The denied host is assembled from fragments so no file in the repository contains it (license:scan, DL-506, scans
// tools/ for the literal host; the tools/ci/fixtures/ exemption does not reach this directory). The fixture file spells
// the vendor as ${MB} and is filled in here.
const MB = ['map', 'box'].join('');
const MB_API = `https://api.${MB}.com`;
const denied = JSON.parse(readFileSync(new URL('./fixtures/sources.denied-host.json', import.meta.url), 'utf8').replaceAll('${MB}', MB)) as SourcesConfig;

const cfg = loadSources();
// The three credit lines of the Terrain Tiles data over the bake boxes, in this order (DL-711): the 3DEP line, then the two lines
// the attribution document requires verbatim for the USGS and NOAA datasets; the registry citation follows when the lock is committed.
const TERRAIN_CREDIT = [
  '3DEP data courtesy of the U.S. Geological Survey',
  'United States 3DEP (formerly NED) and global GMTED2010 and SRTM terrain data courtesy of the U.S. Geological Survey.',
  'Global ETOPO1 terrain data U.S. National Oceanic and Atmospheric Administration',
].join('. ').replace('Survey.. ', 'Survey. ');
const clone = (): SourcesConfig => JSON.parse(JSON.stringify(cfg)) as SourcesConfig;

describe('attribution.world.json (AC-6)', () => {
  it('is regenerated byte for byte from sources.json and the committed sf lock', () => {
    expect(readFileSync(ATTRIBUTION_PATH, 'utf8')).toBe(stableJson(buildAttribution(cfg)));
  });

  it('credits OSM, DataSF and the USGS 3DEP terrain with their licence and licence URL', () => {
    const by = new Map(buildAttribution(cfg).entries.map((e) => [e.id, e]));
    expect(by.get('osm')).toMatchObject({ text: '© OpenStreetMap contributors', licence: 'ODbL-1.0', licenceUrl: 'https://opendatacommons.org/licenses/odbl/1-0/' });
    expect(by.get('datasf-footprints')).toMatchObject({ text: 'City and County of San Francisco', licence: 'PDDL-1.0', licenceUrl: 'https://opendatacommons.org/licenses/pddl/1-0/' });
    expect(by.get('sfmta-patterns')!.text).toBe('City and County of San Francisco, SFMTA');
    expect(by.get('datasf-trees')!.text).toBe('City and County of San Francisco, SF Public Works');
    expect(by.get('terrarium')).toMatchObject({
      licence: 'LicenseRef-PublicDomain-USGov',
      licenceUrl: 'https://registry.opendata.aws/terrain-tiles',
    });
    expect(by.get('terrarium')!.text.startsWith('3DEP data courtesy of the U.S. Geological Survey')).toBe(true);
    // DL-711: the credit lines the Terrain Tiles attribution document requires for the datasets behind the bake boxes
    expect(by.get('terrarium')!.text).toContain('United States 3DEP (formerly NED) and global GMTED2010 and SRTM terrain data courtesy of the U.S. Geological Survey.');
    expect(by.get('terrarium')!.text).toContain('Global ETOPO1 terrain data U.S. National Oceanic and Atmospheric Administration');
    for (const e of by.values()) {
      expect(Object.keys(e).sort()).toEqual(['id', 'licence', 'licenceUrl', 'source', 'surfaces', 'text']);
      expect(e.surfaces.length).toBeGreaterThan(0);
    }
  });

  it('adds the registry citation with the date of the committed sf lock, and none without a lock', () => {
    const lock = JSON.parse(readFileSync(path.join(repoRoot, 'content/world/raw.lock.sf.json'), 'utf8')) as { sources: { id: string; retrievedAt: string }[] };
    const date = lock.sources.find((s) => s.id === 'terrarium')!.retrievedAt.slice(0, 10);
    const withLock = buildAttribution(cfg).entries.find((e) => e.id === 'terrarium')!;
    expect(withLock.text).toBe(`${TERRAIN_CREDIT}. Terrain Tiles was accessed on ${date} from https://registry.opendata.aws/terrain-tiles`);
    expect(terrariumAccessDate()).toBe(date);
    expect(terrariumAccessDate(path.join(tmpdir(), 'dv-no-such-lock.json'))).toBeNull();
    expect(buildAttribution(cfg, null).entries.find((e) => e.id === 'terrarium')!.text).toBe(TERRAIN_CREDIT);
  });

  it('lists every source and no excluded one (3D Tiles, Mapbox)', () => {
    const entries = buildAttribution(cfg).entries;
    expect(entries.map((e) => e.id)).toEqual(cfg.sources.map((s) => s.id).sort());
    const text = JSON.stringify(entries).toLowerCase();
    expect(text).not.toMatch(/mapbox|googleapis|photorealistic|3d tiles/);
  });

  it('copies only the entries of an area into its bake', () => {
    expect(attributionFor(cfg, 'civic-excerpt').entries.map((e) => e.id)).toEqual(['datasf-footprints', 'sfmta-patterns', 'sfmta-stops', 'datasf-neighborhoods', 'datasf-parks', 'datasf-streets', 'datasf-trees', 'osm', 'terrarium']);
    expect(attributionFor(cfg, 'sf').entries).toHaveLength(10);
  });

  it('has a licence text for the new record licence and allowlists it', () => {
    const allow = JSON.parse(readFileSync(path.join(repoRoot, 'config/license-allowlist.json'), 'utf8')) as { record: string[] };
    expect(allow.record).toContain('LicenseRef-PublicDomain-USGov');
    const txt = readFileSync(path.join(repoRoot, 'LICENSES/LicenseRef-PublicDomain-USGov.txt'), 'utf8');
    expect(txt).toContain('3DEP data courtesy of the U.S. Geological Survey');
    expect(txt).toContain('https://registry.opendata.aws/terrain-tiles');
  });
});

describe('sources.schema.json (DL-676)', () => {
  it('accepts config/world/sources.json', () => {
    expect(validateSources(JSON.parse(readFileSync(path.join(repoRoot, 'config/world/sources.json'), 'utf8')))).toEqual([]);
  });

  it('rejects the fixture with an api.<vendor>.com URL (DL-676)', () => {
    const errors = validateSources(denied);
    expect(errors.length).toBeGreaterThan(0);
    expect(errors.join('\n')).toMatch(/url/);
  });

  it.each([
    `${MB_API}/v4/x`,
    'https://mapbox.com/x',
    'https://tiles.mapbox.com:443/x',
    'https://tile.googleapis.com/v1/3dtiles/root.json',
    'https://user@tile.googleapis.com/v1/x',
    'http://data.sf.gov/resource/x.json',
  ])('rejects the source URL %s', (url) => {
    const c = clone();
    c.sources[0]!.url = url;
    expect(validateSources(c).length).toBeGreaterThan(0);
  });

  it('rejects a denied licence URL too, and accepts look-alike hosts', () => {
    const c = clone();
    c.sources[1]!.licenceUrl = `${MB_API}/terms`;
    expect(validateSources(c).length).toBeGreaterThan(0);
    const ok = clone();
    ok.sources[0]!.url = 'https://notmapbox.com/x.json';
    expect(validateSources(ok)).toEqual([]);
  });

  it('refuses the same hosts at fetch time, before any request', async () => {
    expect(isDeniedHost('https://a.b.mapbox.com/x')).toBe(true);
    expect(isDeniedHost('https://tile.googleapis.com/x')).toBe(true);
    expect(isDeniedHost('https://data.sf.gov/x')).toBe(false);
    expect(isDeniedHost('not a url')).toBe(true);
    await expect(fetchBuffer(`${MB_API}/x`)).rejects.toThrow(/never sources/);
    await expect(fetchBuffer('https://tile.googleapis.com/x')).rejects.toThrow(/never sources/);
  });
});

describe('map:fetch', () => {
  it('prints SKIP offline for every source of sf and writes nothing (AC-7)', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'dv-fetch-'));
    const rawDir = path.join(dir, 'raw');
    const contentDir = path.join(dir, 'content');
    const lines: string[] = [];
    const code = await runFetch({ area: 'sf', cfg, env: { DV_MAP_OFFLINE: '1' }, rawDir, contentDir, log: (l) => lines.push(l) });
    expect(code).toBe(0);
    expect(lines).toEqual(cfg.areas.sf.sources.map((id) => `SKIP map:fetch ${id}: offline`));
    expect(existsSync(rawDir)).toBe(false);
    expect(existsSync(contentDir)).toBe(false);
  });

  it('fills the osmium commands exactly as recorded in sources.json', () => {
    const cmds = osmCommands(cfg, '/raw', '/raw/norcal.osm.pbf');
    expect(cmds[0]).toBe('osmium extract --bbox=-122.55,37.68,-122.3,37.89 --strategy=complete_ways --overwrite -o /raw/osm-sf.osm.pbf /raw/norcal.osm.pbf');
    expect(cmds[1]).toContain('osmium tags-filter');
    // DL-708: the landmark Source ids are merged back into the tag-filtered extract before the export
    expect(cmds[2]).toBe('osmium getid --overwrite --add-referenced -i /raw/landmark-ids.txt -o /raw/osm-sf-landmarks.osm.pbf /raw/osm-sf.osm.pbf');
    expect(cmds[3]).toBe('osmium merge --overwrite -o /raw/osm-sf-merged.osm.pbf /raw/osm-sf-tags.osm.pbf /raw/osm-sf-landmarks.osm.pbf');
    expect(cmds[4]).toContain('osmium export');
    expect(cmds[4]).toContain('/raw/osm-sf-merged.osm.pbf');
    expect(cmds.join(' ')).not.toMatch(/\{[a-zA-Z.]+\}/);
    expect(osmCommands(cfg, '/raw', '/raw/n.pbf', true)[0]).toContain('--bbox=-122.6,37.3,-121.8,38');
    expect(fillCommand('a {x} {y}', { x: 1 })).toBe('a 1 {y}');
  });

  it('leaves the committed civic-excerpt alone without --fixture', async () => {
    const lines: string[] = [];
    expect(await runFetch({ area: 'civic-excerpt', cfg, env: {}, log: (l) => lines.push(l) })).toBe(0);
    expect(lines.join('\n')).toMatch(/committed/);
  });
});
