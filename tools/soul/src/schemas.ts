/**
 * npc:schemas. Generates, from the hand-written JSON Schemas in packages/shared/schemas/npc/:
 *  - packages/shared/src/npc/validators.gen.ts: Ajv standalone ESM validators (no runtime code generation);
 *  - packages/shared/schemas/npc/soul-1.0.llm.schema.json: the structured-output subset the soul generator writes
 *    (spec/domains/04-npc-builder.md section C4): numeric, length, format and pattern keywords stripped, conditionals
 *    removed, optional fields flattened to required-nullable.
 * `--check` regenerates both in memory and fails on any difference from the files on disk.
 *
 *   tsx tools/soul/src/cli.ts schemas [--check]
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

export const SCHEMA_DIR = 'packages/shared/schemas/npc';
export const VALIDATORS_PATH = 'packages/shared/src/npc/validators.gen.ts';
export const LLM_SCHEMA_PATH = `${SCHEMA_DIR}/soul-1.0.llm.schema.json`;

/** Export name -> schema file (and optional fragment) compiled into validators.gen.ts. */
export const VALIDATORS: Record<string, { file: string; fragment?: string }> = {
  validateSoulFrontmatter: { file: 'soul-1.0.schema.json' },
  validateRosterManifest: { file: 'npc-roster-1.0.schema.json' },
  validateRosterBundle: { file: 'npc-roster-1.0.schema.json', fragment: '#/$defs/bundle' },
  validateNpcTurn: { file: 'npc-turn-1.0.schema.json' },
  validateNpcIntent: { file: 'npc-intent-1.0.schema.json' },
  validateNpcSummary: { file: 'npc-summary-1.0.schema.json' },
  validateDialogueRequest: { file: 'dialogue-request-1.0.schema.json' },
  validateVoiceCatalog: { file: 'voice-catalog-1.0.schema.json' },
  validateBarkPool: { file: 'bark-pool-1.0.schema.json' },
};

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };
type Obj = { [k: string]: Json };

function readJson(root: string, rel: string): Obj {
  return JSON.parse(readFileSync(path.join(root, rel), 'utf8')) as Obj;
}

