/** Ajv standalone code requires two small runtime helpers; the shared package imports nothing, so they are inlined. */
const RUNTIME_INLINE: Record<string, string> = {
  'ajv/dist/runtime/equal': `function __dvEqual(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    if (a.constructor !== b.constructor) return false;
    if (Array.isArray(a)) {
      if (a.length !== b.length) return false;
      for (let i = 0; i < a.length; i++) if (!__dvEqual(a[i], b[i])) return false;
      return true;
    }
    const ka = Object.keys(a);
    if (ka.length !== Object.keys(b).length) return false;
    for (const k of ka) if (!Object.prototype.hasOwnProperty.call(b, k) || !__dvEqual(a[k], b[k])) return false;
    return true;
  }
  return a !== a && b !== b;
}`,
  'ajv/dist/runtime/ucs2length': `function __dvUcs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      const next = str.charCodeAt(pos);
      if ((next & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}`,
};
const RUNTIME_NAME: Record<string, string> = { 'ajv/dist/runtime/equal': '__dvEqual', 'ajv/dist/runtime/ucs2length': '__dvUcs2length' };

function inlineRuntime(code: string): string {
  let out = code;
  const used: string[] = [];
  out = out.replace(/require\("(ajv\/[^"]+)"\)\.default/g, (_m, mod: string) => {
    const name = RUNTIME_NAME[mod];
    if (!name) throw new Error(`generated validators need ${mod}, which is not inlined`);
    if (!used.includes(mod)) used.push(mod);
    return name;
  });
  const left = out.match(/(?:from\s+|require\()["']ajv[^"']*["']/g);
  if (left) throw new Error(`generated validators import from ajv at runtime: ${left.join(', ')}`);
  return [...used.map((m) => RUNTIME_INLINE[m] as string), out].join('\n');
}

export function generateValidators(root: string): string {
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true, optimize: true } });
  const ids = new Map<string, string>();
  const files = [...new Set(Object.values(VALIDATORS).map((v) => v.file))].sort();
  for (const f of files) {
    const schema = readJson(root, `${SCHEMA_DIR}/${f}`);
    ajv.addSchema(schema as object);
    ids.set(f, String(schema.$id));
  }
  const refs: Record<string, string> = {};
  for (const [name, v] of Object.entries(VALIDATORS)) refs[name] = `${ids.get(v.file)}${v.fragment ?? ''}`;
  const code = inlineRuntime(standaloneCode(ajv, refs));
  return [
    '// Generated by `pnpm npc:schemas` from packages/shared/schemas/npc/*.schema.json (Ajv standalone, ESM). Do not edit.',
    '// Machine output: eslint.config.js ignores *.gen.ts and the file is outside the type-checker (BD-M06a2-02).',
    '/* eslint-disable */',
    '// @ts-nocheck',
    code.trimEnd(),
    '',
  ].join('\n');
}

