// soul-1.0.llm.schema.json

const STRIP = new Set([
  'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'multipleOf', 'minLength', 'maxLength', 'minItems', 'maxItems',
  'uniqueItems', 'minProperties', 'maxProperties', 'format', 'pattern', 'if', 'then', 'else', 'allOf', 'contains', '$schema', '$id', '$defs',
]);

const nullable = (s: Json): Json => ({ anyOf: [s, { type: 'null' }] });

/** Inlines $ref against the root $defs and removes the keywords structured outputs do not accept. */
function simplify(node: Json, root: Obj): Json {
  if (Array.isArray(node)) return node.map((n) => simplify(n, root));
  if (node === null || typeof node !== 'object') return node;
  const ref = node.$ref;
  if (typeof ref === 'string') {
    const m = /^#\/\$defs\/(.+)$/.exec(ref);
    const target = m ? ((root.$defs as Obj | undefined)?.[m[1] as string] as Json | undefined) : undefined;
    if (target === undefined) throw new Error(`unresolved $ref ${ref}`);
    return simplify(target, root);
  }
  const out: Obj = {};
  for (const [k, v] of Object.entries(node)) {
    if (STRIP.has(k)) continue;
    if (k === 'properties' && v && typeof v === 'object' && !Array.isArray(v)) {
      const props: Obj = {};
      for (const [pk, pv] of Object.entries(v)) props[pk] = simplify(pv as Json, root);
      out[k] = props;
    } else out[k] = simplify(v, root);
  }
  // "type": ["string","null"] becomes anyOf so the null branch is explicit.
  if (Array.isArray(out.type)) {
    const t = (out.type as string[]).filter((x) => x !== 'null');
    if (t.length === 1 && (out.type as string[]).includes('null')) {
      const { type: _drop, ...rest } = out;
      return { anyOf: [{ ...rest, type: t[0] as string }, { type: 'null' }] };
    }
  }
  return out;
}

/** Makes every property required; the ones the source marks optional become nullable. */
function flatten(node: Json): Json {
  if (Array.isArray(node)) return node.map(flatten);
  if (node === null || typeof node !== 'object') return node;
  const out: Obj = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === 'properties' && v && typeof v === 'object' && !Array.isArray(v)) {
      const required = new Set((node.required as string[] | undefined) ?? []);
      const props: Obj = {};
      for (const [pk, pv] of Object.entries(v)) {
        const f = flatten(pv as Json);
        props[pk] = required.has(pk) ? f : nullable(f);
      }
      out[k] = props;
    } else out[k] = flatten(v);
  }
  if (out.properties) out.required = Object.keys(out.properties as Obj);
  return out;
}

const str = (description?: string): Obj => (description ? { type: 'string', description } : { type: 'string' });
const strList = (description?: string): Obj => ({ type: 'array', items: str(), ...(description ? { description } : {}) });

export function deriveLlmSchema(soul: Obj): Obj {
  const sp = (soul.properties as Obj) ?? {};
  const pick = (key: string): Json => simplify(sp[key] as Json, soul);
  const obj = (properties: Obj): Obj => ({ type: 'object', additionalProperties: false, required: Object.keys(properties), properties });

  const knowledge = pick('knowledge') as Obj;
  const kProps = { ...(knowledge.properties as Obj) };
  delete kProps.realWorldRefs;

  const locations = pick('locations') as Obj;
  const lProps = locations.properties as Obj;
  const rails = pick('rails') as Obj;
  const rProps = rails.properties as Obj;

  const schedule = pick('schedule') as Obj;
  const block = ((schedule.items as Obj).properties as Obj);
  block.from = str('HH:MM, 24-hour game time');
  block.to = str('HH:MM, 24-hour game time; 24:00 ends the day');
  block.place = str('a PoiId from the provided list of the district');

  const body = obj({
    shortBio: str('at most 280 characters'),
    speech: pick('speech'),
    personality: pick('personality'),
    knowledge: obj(kProps),
    locations: obj({ home: lProps.home as Json, hangouts: lProps.hangouts as Json }),
    schedule,
    goals: { ...(pick('goals') as Obj), description: 'only goals from the provided catalog' },
    visual_brief: str('text-only appearance; never real names, logos or photographs'),
    rails: obj({ forbiddenTopics: rProps.forbiddenTopics as Json, never: rProps.never as Json, deflectionStyle: rProps.deflectionStyle as Json }),
    sections: obj({
      identity: str(), voice: str(), personality: str(), knowledge: str(), placesAndSchedule: str(), rails: str(),
      exampleLines: {
        type: 'array',
        items: obj({ tag: { enum: ['greeting', 'mission', 'deflect', 'threat', 'farewell'] }, text: str() }),
      },
    }),
    realPersonSuspected: { type: 'boolean' },
    namedPeople: strList('names of real people the backstory mentions'),
  });
  const flat = flatten(body) as Obj;
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'soul-1.0.llm',
    description: 'Generated by pnpm npc:schemas from soul-1.0.schema.json. Do not edit.',
    ...flat,
  };
}

export function llmSchemaText(root: string): string {
  return `${JSON.stringify(deriveLlmSchema(readJson(root, `${SCHEMA_DIR}/soul-1.0.schema.json`)), null, 2)}\n`;
}

const NUMERIC_LENGTH_FORMAT = ['minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'multipleOf', 'minLength', 'maxLength', 'minItems', 'maxItems', 'format'];

/** Counts for the structured-output limits (research/ai-npc-runtime.md section 1.5): optional parameters and union-typed ones. */
export function llmSchemaStats(schema: Json): { optional: number; unions: number; forbidden: string[] } {
  let optional = 0;
  let unions = 0;
  const forbidden: string[] = [];
  const walk = (n: Json, at: string): void => {
    if (Array.isArray(n)) return n.forEach((x, i) => walk(x, `${at}/${i}`));
    if (n === null || typeof n !== 'object') return;
    if (n.properties && typeof n.properties === 'object') {
      const req = new Set((n.required as string[] | undefined) ?? []);
      optional += Object.keys(n.properties).filter((k) => !req.has(k)).length;
    }
    if (n.anyOf || n.oneOf) unions++;
    if (Array.isArray(n.type)) unions++;
    for (const [k, v] of Object.entries(n)) {
      const isKeyword = !(at.endsWith('/properties') || at.endsWith('/$defs'));
      if (isKeyword && NUMERIC_LENGTH_FORMAT.includes(k)) forbidden.push(`${at}/${k}`);
      walk(v, `${at}/${k}`);
    }
  };
  walk(schema, '');
  return { optional, unions, forbidden };
}

