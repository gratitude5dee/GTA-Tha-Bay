export interface SchemasResult { ok: boolean; messages: string[] }

export function runSchemas(root: string, check: boolean): SchemasResult {
  const outputs: [rel: string, text: string][] = [
    [VALIDATORS_PATH, generateValidators(root)],
    [LLM_SCHEMA_PATH, llmSchemaText(root)],
  ];
  const messages: string[] = [];
  let ok = true;
  for (const [rel, text] of outputs) {
    const abs = path.join(root, rel);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (check) {
      if (current !== text) {
        ok = false;
        messages.push(`npc:schemas: drift in ${rel}${current === null ? ' (missing)' : ''}; run pnpm npc:schemas`);
      } else messages.push(`npc:schemas: ${rel} is up to date`);
    } else {
      if (current !== text) {
        mkdirSync(path.dirname(abs), { recursive: true });
        writeFileSync(abs, text);
      }
      messages.push(`npc:schemas: ${current === text ? 'unchanged' : 'wrote'} ${rel}`);
    }
  }
  return { ok, messages };
}
