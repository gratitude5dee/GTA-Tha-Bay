/**
 * Dependencies the handlers take by injection (M00e, DL-611; M05d adds the data port and the shipped cutscene index): tests pass a stub
 * admin path, a clock, a log sink and a DataPort; production code uses the defaults and never overrides `ADMIN_PATH`.
 */
import type { CutsceneIndex } from '@dv/shared/contracts/c09-cutscene';
import type { ServerDataPort } from '@dv/shared/data-port';
import { configuredDataPort } from './data/index.ts';
import type { Env } from './env.ts';
import shippedIndex from './generated/cutscene-index.json';

/** Which Supabase Auth admin calls are recorded as verified in spec/03 section 7 (U-ACCT-3, U-ACCT-6). */
export interface AdminPath {
  /** Create a user with app-level metadata in the same call. */
  create: boolean;
  /** Update a user's app-level metadata. */
  updateMeta: boolean;
  /** Read and delete one user. */
  getDelete: boolean;
}

export interface AppDeps {
  adminPath: AdminPath;
  /** One log line. Never receives a password, token, username or network address. */
  log: (line: string) => void;
  /** Logs `line` the first time `key` is seen for this app instance (once per isolate in production). */
  logOnce: (key: string, line: string) => void;
  /** Epoch ms. */
  now: () => number;
  /** The database, or null when none is configured (the static fallback applies). */
  data: (env: Env) => ServerDataPort | null;
  /** The cutscene index shipped in the Worker bundle (generated by `pnpm assets:cutscene-index`). */
  cutsceneIndex: () => CutsceneIndex;
}

export function makeDeps(adminPath: AdminPath, overrides: Partial<Omit<AppDeps, 'adminPath'>> = {}): AppDeps {
  const log = overrides.log ?? ((line: string) => console.log(line));
  const seen = new Set<string>();
  return {
    adminPath,
    log,
    logOnce:
      overrides.logOnce ??
      ((key, line) => {
        if (seen.has(key)) return;
        seen.add(key);
        log(line);
      }),
    now: overrides.now ?? (() => Date.now()),
    data: overrides.data ?? ((env) => configuredDataPort(env)),
    cutsceneIndex: overrides.cutsceneIndex ?? (() => shippedIndex as unknown as CutsceneIndex),
  };
}
