// ESLint flat config. The C02 determinism rules (config/eslint/determinism.mjs) apply to sim source only; tests,
// scripts and fixtures are outside the scope. no-glsl-in-engine applies to packages/**.
import { defineConfig, globalIgnores } from 'eslint/config';
import tseslint from 'typescript-eslint';

import { GLSL_SYNTAX, SIM_FILES, SIM_IGNORES, THIRD_PARTY_IMPORT_PATTERN, determinismConfig } from './config/eslint/determinism.mjs';

const IDENTITY_IMPORT_PATTERN = { regex: '^@dv/identity(?:/|$)', message: 'services/** may not import @dv/identity: it is client-only (M04b3).' };

export default defineConfig([
  globalIgnores([
    '**/node_modules/**',
    '**/dist/**',
    '**/.wrangler/**',
    'test-results/**',
    'playwright-report/**',
    '.spike/**',
    '.claude/**',
    'third_party/**', // vendored files are not ours to lint (ADR-REUSE-01)
    'spec/**',
    'research/**',
    'prompt-pack/**',
    'docs/**',
    'apps/web/public/**',
    '**/*.gen.ts', // generated by pnpm npc:schemas (Ajv standalone output, M06a2)
  ]),
  ...tseslint.configs.recommended,
  {
    rules: {
      '@typescript-eslint/no-unused-vars': ['error', { argsIgnorePattern: '^_', varsIgnorePattern: '^_' }],
      '@typescript-eslint/consistent-type-imports': ['error', { fixStyle: 'inline-type-imports' }],
    },
  },
  {
    files: ['packages/**/*.{ts,tsx}'],
    rules: { 'no-restricted-syntax': ['error', ...GLSL_SYNTAX] },
  },
  {
    // The HTMLVideoElement shim is an intentionally empty interface that merges with lib.dom (DL-232).
    files: ['packages/shared/src/contracts/dom-media.d.ts'],
    rules: { '@typescript-eslint/no-empty-object-type': 'off' },
  },
  {
    // Ported code is copied, never imported. The tools that read vendored data to write derived files may import.
    files: ['**/*.{ts,tsx,js,mjs,cjs,mts,cts}'],
    ignores: ['tools/{map,assets,ci,soul}/**'],
    rules: { 'no-restricted-imports': ['error', { patterns: [THIRD_PARTY_IMPORT_PATTERN] }] },
  },
  {
    // M04b3: @dv/identity is client-only and imports only @dv/shared; no services/** file imports it. Placed before the edge blocks,
    // which repeat IDENTITY_IMPORT_PATTERN because a later matching block replaces the options of an earlier no-restricted-imports.
    files: ['packages/identity/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            THIRD_PARTY_IMPORT_PATTERN,
            { regex: '^@dv/(?!shared(?:/|$))', message: '@dv/identity may import only @dv/shared (M04b3).' },
            { regex: '^(?:\\.\\./){2,}', message: '@dv/identity may not import by a relative path that leaves the package (M04b3).' },
          ],
        },
      ],
    },
  },
  {
    files: ['services/**/*.{ts,tsx}'],
    rules: { 'no-restricted-imports': ['error', { patterns: [THIRD_PARTY_IMPORT_PATTERN, IDENTITY_IMPORT_PATTERN] }] },
  },
  ...edgeImportRules(),
  determinismConfig(SIM_FILES, SIM_IGNORES),
]);

/**
 * services/edge/src may not import by a relative path that leaves services/edge/, except the three config files the Worker
 * reads (M00e, DL-514, DL-602, DL-644). Package imports (`@dv/*`) are not relative and are unaffected. One block per directory
 * depth, because "leaving services/edge/" is a different number of `../` at each depth. A later flat-config block replaces the options
 * of an earlier `no-restricted-imports`, so each block repeats the third_party pattern of M00f.
 */
function edgeImportRules() {
  const allowed = '(?!(?:\\.\\./)*config/(?:brand\\.ts|ip-denylist\\.json|terms\\.ts)$)';
  return [1, 2, 3].map((depth) => ({
    files: [`services/edge/src/${'*/'.repeat(depth - 1)}*.ts`],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            THIRD_PARTY_IMPORT_PATTERN,
            IDENTITY_IMPORT_PATTERN,
            {
              regex: `^(?:\\.\\./){${depth + 1},}${allowed}`,
              message:
                'services/edge/src may import only config/brand.ts, config/ip-denylist.json and config/terms.ts from outside services/edge/ (M00e).',
            },
          ],
        },
      ],
    },
  }));
}
